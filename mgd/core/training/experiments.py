"""实验管理：run 目录扫描、多 run 横向对比、CSV / LaTeX 导出。"""
from __future__ import annotations

import csv
import json
from pathlib import Path
from typing import Any

from ..config import Settings, get_settings

COMPARE_COLUMNS = (
    "run_id", "arch", "epochs", "best_metric", "best_epoch", "val_dice", "peak_vram_gb",
    "samples_per_second", "wall_seconds", "split_signature", "verified", "created_at",
)


def runs_root(settings: Settings) -> Path:
    return settings.output_dir / "runs"


def _load_json(path: Path) -> dict:
    if not path.is_file():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}


def run_summary(run_dir: Path) -> dict[str, Any]:
    result = _load_json(run_dir / "run_result.json")
    env = _load_json(run_dir / "env.json")
    reference = _load_json(run_dir / "reference_report.json")
    config_path = run_dir / "config.yaml"
    config_text = config_path.read_text(encoding="utf-8") if config_path.is_file() else ""
    config: dict = {}
    if config_text:
        try:
            import yaml

            config = yaml.safe_load(config_text) or {}
        except Exception:
            config = {}
    train = (config.get("train_config") or {})
    metrics = reference.get("metrics") or {}
    return {
        "run_id": run_dir.name,
        "path": str(run_dir),
        "arch": result.get("arch") or train.get("model_name") or "",
        "epochs": result.get("epochs_run") or train.get("epochs") or 0,
        "best_metric": result.get("best_metric"),
        "best_epoch": result.get("best_epoch"),
        "val_dice": (metrics.get("dice") or {}).get("mean"),
        "peak_vram_gb": result.get("peak_vram_gb"),
        "samples_per_second": result.get("samples_per_second"),
        "wall_seconds": result.get("wall_seconds"),
        "split_signature": reference.get("split_signature") or _split_signature_from_config(config),
        "verified": bool(reference.get("valid")),
        "created_at": env.get("created_at") or "",
        "pretrained": (train.get("pretrained")),
        "model_name": train.get("model_name") or "",
    }


def _split_signature_from_config(config: dict) -> str:
    split = config.get("resolved_yaml", {}).get("data", {})
    return "" if not split else ""


def list_runs(settings: Settings | None = None) -> list[dict[str, Any]]:
    settings = settings or get_settings()
    root = runs_root(settings)
    if not root.is_dir():
        return []
    summaries = [run_summary(path) for path in sorted(root.iterdir()) if path.is_dir()]
    return sorted(summaries, key=lambda item: item["run_id"], reverse=True)


def compare_runs(run_ids: list[str], settings: Settings | None = None) -> list[dict[str, Any]]:
    settings = settings or get_settings()
    root = runs_root(settings)
    chosen = [root / run_id for run_id in run_ids] if run_ids else [
        path for path in sorted(root.iterdir()) if path.is_dir()
    ]
    return [run_summary(path) for path in chosen if path.is_dir()]


def compare_rows(summaries: list[dict[str, Any]]) -> list[list[Any]]:
    rows: list[list[Any]] = []
    for item in summaries:
        rows.append([
            item["run_id"],
            item["arch"],
            item["epochs"],
            _fmt(item["best_metric"], 4),
            item["best_epoch"],
            _fmt(item["val_dice"], 4),
            _fmt(item["peak_vram_gb"], 3),
            _fmt(item["samples_per_second"], 2),
            _fmt(item["wall_seconds"], 1),
            (item["split_signature"] or "")[:12],
            "是" if item["verified"] else "否（草稿）",
            item["created_at"],
        ])
    return rows


def _fmt(value: Any, digits: int) -> str:
    try:
        if value is None:
            return "N/A"
        return f"{float(value):.{digits}f}"
    except (TypeError, ValueError):
        return "N/A"


def export_comparison_csv(summaries: list[dict[str, Any]], path: str | Path) -> Path:
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    with target.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(COMPARE_COLUMNS)
        for item in summaries:
            writer.writerow([item.get(key, "") for key in COMPARE_COLUMNS])
    return target


def export_comparison_latex(summaries: list[dict[str, Any]], path: str | Path) -> Path:
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    header = " & ".join(COMPARE_COLUMNS) + r" \\"
    lines = [
        r"\begin{table}[htbp]",
        r"\centering",
        r"\caption{Multi-run comparison (generated by mgd-seg)}",
        r"\begin{tabular}{" + "l" * len(COMPARE_COLUMNS) + "}",
        r"\hline",
        header,
        r"\hline",
    ]
    for item in summaries:
        cells = []
        for key in COMPARE_COLUMNS:
            value = item.get(key, "")
            if isinstance(value, float):
                value = f"{value:.4f}"
            text = str(value).replace("_", r"\_").replace("%", r"\%")
            cells.append(text)
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\hline", r"\end{tabular}", r"\end{table}", ""]
    target.write_text("\n".join(lines), encoding="utf-8")
    return target


def metric_series(run_dir: str | Path) -> list[dict[str, Any]]:
    path = Path(run_dir) / "metrics.jsonl"
    records: list[dict[str, Any]] = []
    if path.is_file():
        for line in path.read_text(encoding="utf-8").splitlines():
            try:
                records.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    return records
